"""``scores.score`` INT -> REAL so ``/score set|add`` accept fractional points.

Hand-written: aerich refuses ``MODIFY COLUMN`` on SQLite, so this does the
standard SQLite table rebuild (create new, copy, drop old, rename). Nothing
holds an FK into ``scores``, so the drop/rename doesn't touch other tables.
The downgrade truncates fractional scores back to integers.
"""

from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


def _rebuild(score_type: str, score_expr: str) -> str:
    return f"""
        CREATE TABLE "_scores_new" (
    "id" CHAR(36) NOT NULL PRIMARY KEY,
    "score" {score_type} NOT NULL,
    "discord_account_id" CHAR(36) NOT NULL REFERENCES "discord_accounts" ("id") ON DELETE CASCADE,
    "event_id" CHAR(36) NOT NULL REFERENCES "weekly_events" ("id") ON DELETE CASCADE,
    CONSTRAINT "uid_scores_event_i_379816" UNIQUE ("event_id", "discord_account_id")
);
        INSERT INTO "_scores_new" ("id", "score", "discord_account_id", "event_id")
            SELECT "id", {score_expr}, "discord_account_id", "event_id" FROM "scores";
        DROP TABLE "scores";
        ALTER TABLE "_scores_new" RENAME TO "scores";"""


async def upgrade(db: BaseDBAsyncClient) -> str:
    return _rebuild("REAL", 'CAST("score" AS REAL)')


async def downgrade(db: BaseDBAsyncClient) -> str:
    return _rebuild("INT", 'CAST("score" AS INTEGER)')


